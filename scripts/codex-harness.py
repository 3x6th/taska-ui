#!/usr/bin/env python3
"""Taska's Codex role adapter. Python 3.11+, no third-party dependencies."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import sys
import tempfile
import tomllib
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parent.parent
ROLES = ("frontend-builder", "art-director", "api-contract-guard", "release-reviewer")
BINDING = """\n\nCodex runtime binding (does not replace the role above):
Read docs/ai/CODEX.md. Use the same authority order and staged reviews.
Only frontend-builder may edit production frontend code. Other roles return
their verdict as the final response; the launcher saves it. Never file Jira,
push, commit, merge, or change external systems. Ask the orchestrator for any
missing contract, story, browser evidence or external read. Do not invent it.
A native spawned consultation is not a gated reviewer verdict: reviewers must
run through scripts/codex-harness.py run in a separate read-only process.
Report every blocker and at most three non-blocking findings.
"""


def source_role(role):
    source = (ROOT / ".claude/agents" / f"{role}.md").read_text()
    _, header, body = source.split("---\n", 2)
    metadata = dict(line.split(": ", 1) for line in header.strip().splitlines())
    if metadata["name"] != role:
        raise ValueError(f"Role name mismatch: {role}")
    return metadata, body.lstrip("\n")


def generated_role(role):
    metadata, body = source_role(role)
    return (
        "# Generated by scripts/codex-harness.py sync; edit .claude/agents instead.\n"
        "# Reviewer isolation is enforced by the launcher, not this TOML file.\n"
        f"name = {json.dumps(role)}\n"
        f"description = {json.dumps(metadata['description'])}\n"
        'model_reasoning_effort = "high"\n'
        f"developer_instructions = {json.dumps(body + BINDING, ensure_ascii=False)}\n"
        "[features]\napps = false\nplugins = false\nmemories = false\n"
        "request_permissions_tool = false\n"
    )


def sync(check=False):
    for role in ROLES:
        target = ROOT / ".codex/agents" / f"{role}.toml"
        expected = generated_role(role)
        if check:
            if not target.exists() or target.read_text() != expected:
                raise ValueError(f"Stale {target.relative_to(ROOT)}; run npm run harness:sync")
            parsed = tomllib.loads(target.read_text())
            if parsed["developer_instructions"] != source_role(role)[1] + BINDING:
                raise ValueError(f"Role body differs: {role}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)


def binary():
    explicit = os.environ.get("TASKA_CODEX_BIN")
    candidates = [explicit] if explicit else [
                  "/Applications/ChatGPT.app/Contents/Resources/codex-cli/bin/codex",
                  "/Applications/Codex.app/Contents/Resources/codex",
                  shutil.which("codex")]
    for candidate in filter(None, candidates):
        if Path(candidate).is_file():
            help_result = subprocess.run([candidate, "exec", "--help"], capture_output=True, text=True)
            if help_result.returncode == 0 and all(
                flag in help_result.stdout for flag in ("--ignore-user-config", "--ephemeral")
            ):
                return candidate
    raise RuntimeError("No compatible Codex CLI. Set TASKA_CODEX_BIN to a current installation; no automatic install or unsafe fallback.")


def probe(executable):
    """Exercise the actual OS boundary on disposable files and a local socket."""
    evidence = ROOT / "docs/ai/evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="codex-readonly-", dir=evidence) as directory:
        fixture = Path(directory) / "existing.txt"
        fixture.write_text("unchanged")
        listener = socket.create_server(("127.0.0.1", 0))
        port = listener.getsockname()[1]
        code = r'''
import errno, json, pathlib, socket, sys
fixture = pathlib.Path(sys.argv[1])
results = {"read": fixture.read_text() == "unchanged"}
for key, target in [("overwrite_denied", fixture), ("create_denied", fixture.parent / "new.txt")]:
    try:
        target.write_text("unexpected write")
        results[key] = False
    except OSError as error:
        results[key] = error.errno in (errno.EPERM, errno.EACCES, errno.EROFS)
try:
    with socket.create_connection(("127.0.0.1", int(sys.argv[2])), timeout=2):
        results["network_denied"] = False
except OSError as error:
    results["network_denied"] = error.errno in (errno.EPERM, errno.EACCES)
print(json.dumps(results))
sys.exit(0 if all(results.values()) else 1)
'''
        try:
            result = subprocess.run(
                [executable, "sandbox", "-c", 'sandbox_mode="read-only"',
                 sys.executable, "-c", code, str(fixture), str(port)],
                cwd=ROOT, capture_output=True, text=True, timeout=30,
            )
            if result.returncode != 0 or fixture.read_text() != "unchanged":
                raise RuntimeError(f"Read-only probe failed; do not run a reviewer. {result.stderr.strip()} {result.stdout.strip()}")
            facts = json.loads(result.stdout)
            if not all(facts.get(key) is True for key in ("read", "overwrite_denied", "create_denied", "network_denied")):
                raise RuntimeError("Incomplete read-only probe; no verdict allowed")
            return facts
        finally:
            listener.close()


def child_path():
    # Keep the already compatible interpreter ahead of macOS's Python 3.9.
    # Do not reintroduce the caller's environment or arbitrary PATH entries.
    return os.pathsep.join(dict.fromkeys([
        str(Path(sys.executable).parent), "/opt/homebrew/bin", "/usr/local/bin",
        "/usr/bin", "/bin", "/usr/sbin", "/sbin",
    ]))


def command(executable, role, output):
    # A fresh top-level process is essential: custom subagent settings cannot
    # override an app parent's permissions. No inherited MCP or writable apps.
    return [executable, "exec", "--ignore-user-config", "--ignore-rules", "--ephemeral",
            "--model", os.environ.get("TASKA_CODEX_MODEL", "gpt-6.1-sol"),
            "--sandbox", "workspace-write" if role == "frontend-builder" else "read-only",
            "-c", 'approval_policy="never"',
            "-c", 'model_reasoning_effort="high"',
            "-c", "features.apps=false", "-c", "features.plugins=false",
            "-c", "features.memories=false", "-c", "features.request_permissions_tool=false",
            "-c", "features.image_generation=false", "-c", "features.hooks=false",
            "-c", "features.browser_use=false", "-c", "features.computer_use=false",
            "-c", "agents.enabled=false", "-c", "web_search=\"disabled\"",
            "-c", "skills.bundled.enabled=false", "-c", "skills.include_instructions=false",
            "-c", "shell_environment_policy.inherit=\"none\"",
            "-c", f"shell_environment_policy.set={{PATH={json.dumps(child_path())}}}",
            "-c", "allow_login_shell=false",
            "-C", str(ROOT), "--output-last-message", str(output), "-"]


def run(role, brief, output):
    sync(check=True)
    executable = binary()
    facts = probe(executable) if role != "frontend-builder" else None
    instructions = tomllib.loads((ROOT / ".codex/agents" / f"{role}.toml").read_text())["developer_instructions"]
    brief_text = brief.read_text()
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() or output.with_suffix(".log").exists() or output.with_suffix(".json").exists():
        raise ValueError("Evidence already exists; choose a fresh output path")
    version = subprocess.run([executable, "--version"], capture_output=True, text=True, check=True).stdout.strip()
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    args = command(executable, role, output)
    manifest = {"role": role, "version": version, "executable": executable, "head": head,
                "startedAt": datetime.now(timezone.utc).isoformat(), "probe": facts,
                "instructionsSha256": hashlib.sha256(instructions.encode()).hexdigest(),
                "briefSha256": hashlib.sha256(brief_text.encode()).hexdigest(), "command": args}
    # Parent captures output. The reviewer itself never gets a writable evidence directory.
    with output.with_suffix(".log").open("w") as log:
        result = subprocess.run(args, input=instructions + "\n\nAssigned task:\n" + brief_text,
                                text=True, stdout=log, stderr=subprocess.STDOUT)
    manifest["exitCode"] = result.returncode
    output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n")
    if result.returncode != 0 or not output.exists() or not output.read_text().strip():
        raise RuntimeError(f"Role failed; no verdict. Inspect {output.with_suffix('.log')}")
    print(f"{role}: completed; inspect {output} (completion is not approval)")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    commands.add_parser("sync")
    commands.add_parser("check")
    commands.add_parser("probe")
    launch = commands.add_parser("run")
    launch.add_argument("role", choices=ROLES)
    launch.add_argument("brief", type=Path, help="UTF-8 task, scope, exact diff, evidence paths and Jira acceptance")
    launch.add_argument("--output", type=Path, required=True, help="Fresh local verdict path under docs/ai/reviews")
    args = parser.parse_args()
    if args.action in ("sync", "check"):
        sync(check=args.action == "check")
        print(f"Four Codex roles {'verified' if args.action == 'check' else 'generated'}")
    elif args.action == "probe":
        print(json.dumps(probe(binary()), indent=2))
    else:
        output = args.output.resolve()
        if not output.is_relative_to(ROOT / "docs/ai/reviews") or output.suffix != ".md":
            raise ValueError("Output must be a .md file under docs/ai/reviews")
        run(args.role, args.brief.resolve(), output)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"Codex harness blocked: {error}", file=sys.stderr)
        sys.exit(1)
